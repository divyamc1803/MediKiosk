interface LanguageContextType {
  language: string;
  setLanguage: (lang: string) => void;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLangState] = useState<string>(() => {
    if (typeof window !== 'undefined') {
      return localStorage.getItem('medikiosk_language') || 'en';
    }
    return 'en';
  });

  const setLanguage = (newLang: string) => {
    setLangState(newLang);
    if (typeof window !== 'undefined') {
      localStorage.setItem('medikiosk_language', newLang);
      window.dispatchEvent(new Event('medikiosk-language-change'));
    }
  };

  useEffect(() => {
    const handleStorage = () => {
      const stored = localStorage.getItem('medikiosk_language');
      if (stored && stored !== language) {
        setLangState(stored);
      }
    };

    window.addEventListener('medikiosk-language-change', handleStorage);
    window.addEventListener('storage', handleStorage);
    return () => {
      window.removeEventListener('medikiosk-language-change', handleStorage);
      window.removeEventListener('storage', handleStorage);
    };
  }, [language]);

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[language];
    if (langDict && langDict[key]) return langDict[key];
    if (fallback && langDict && langDict[fallback]) return langDict[fallback];

    // Fallback to Hindi if another Indian language is active and missing a string
    if (language !== 'en' && language !== 'hi') {
      const hiDict = TRANSLATIONS['hi'];
      if (hiDict) {
        if (hiDict[key]) return hiDict[key];
        if (fallback && hiDict[fallback]) return hiDict[fallback];
      }
    }

    const enDict = TRANSLATIONS['en'];
    if (enDict && enDict[key]) return enDict[key];
    if (fallback && enDict && enDict[fallback]) return enDict[fallback];

    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    const current = typeof window !== 'undefined' ? (localStorage.getItem('medikiosk_language') || 'en') : 'en';
    return {
      language: current,
      setLanguage: (l: string) => {
        if (typeof window !== 'undefined') {
          localStorage.setItem('medikiosk_language', l);
          window.dispatchEvent(new Event('medikiosk-language-change'));
        }
      },
      t: (key: string, fallback?: string) => {
        const dict = TRANSLATIONS[current] || TRANSLATIONS['en'];
        return dict?.[key] || (fallback && dict?.[fallback]) || TRANSLATIONS['en']?.[key] || fallback || key;
      },
    };
  }
  return ctx;
}
